/** Create an SVG icon element. */
export function icon(pathD, className = '') {
  const svg = document.createElementNS('http://www.w3.org/2000/svg', 'svg');
  svg.setAttribute('viewBox', '0 0 24 24');
  svg.setAttribute('class', `icon ${className}`.trim());
  svg.innerHTML = pathD;
  return svg;
}

/** Get file type category from extension */
export function getFileTypeCategory(ext) {
  if (!ext) return 'default';
  const e = ext.toLowerCase();
  const map = {
    image: ['jpg', 'jpeg', 'png', 'gif', 'bmp', 'webp', 'svg', 'ico', 'tiff', 'avif'],
    video: ['mp4', 'mkv', 'avi', 'mov', 'wmv', 'flv', 'webm'],
    audio: ['mp3', 'wav', 'flac', 'ogg', 'aac', 'wma', 'm4a'],
    code: ['js', 'ts', 'tsx', 'jsx', 'py', 'rs', 'go', 'c', 'cpp', 'h', 'java', 'html', 'css', 'json', 'xml', 'yaml', 'yml', 'toml', 'md', 'sh', 'bat', 'ps1', 'vue', 'svelte'],
    archive: ['zip', 'rar', '7z', 'tar', 'gz', 'bz2', 'xz'],
    pdf: ['pdf'],
    sheet: ['xls', 'xlsx', 'csv'],
    slides: ['ppt', 'pptx'],
    document: ['doc', 'docx', 'txt', 'rtf', 'odt'],
    exe: ['exe', 'msi', 'app', 'dmg'],
  };
  for (const [type, exts] of Object.entries(map)) {
    if (exts.includes(e)) return type;
  }
  return 'default';
}

/** Minimal stroke file icon element */
export function fileIconEl(file, extraClass = '') {
  const type = file.isDir ? 'folder' : getFileTypeCategory(file.extension);
  const path = FILE_TYPE_ICONS[type] || FILE_TYPE_ICONS.default;
  return icon(path, `file-icon ${type} ${extraClass}`.trim());
}
